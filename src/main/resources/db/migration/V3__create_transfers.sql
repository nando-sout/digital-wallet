CREATE TABLE transfers (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount           NUMERIC(19,2) NOT NULL,
    payer_wallet_id  BIGINT        NOT NULL,
    payee_wallet_id  BIGINT        NOT NULL,
    status           VARCHAR(20)   NOT NULL,
    created_at       TIMESTAMPTZ   NOT NULL,
    rejection_reason VARCHAR(255),

    CONSTRAINT fk_transfers_payer_wallet FOREIGN KEY (payer_wallet_id) REFERENCES wallets (id),
    CONSTRAINT fk_transfers_payee_wallet FOREIGN KEY (payee_wallet_id) REFERENCES wallets (id),
    CONSTRAINT ck_transfers_amount_positive CHECK (amount > 0),
    CONSTRAINT ck_transfers_distinct_wallets CHECK (payer_wallet_id <> payee_wallet_id),
    CONSTRAINT ck_transfers_status CHECK (status IN ('COMPLETED', 'REJECTED'))
);

-- Extrato por carteira ordenado por data. A coluna inicial de cada indice tambem atende
-- as buscas simples por carteira e as verificacoes das FKs (ex.: ao excluir uma carteira),
-- por isso nao ha indices separados apenas em payer_wallet_id ou payee_wallet_id.
CREATE INDEX ix_transfers_payer_wallet_created_at ON transfers (payer_wallet_id, created_at);
CREATE INDEX ix_transfers_payee_wallet_created_at ON transfers (payee_wallet_id, created_at);
